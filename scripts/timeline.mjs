// Lays a story's lines end to end from their real audio lengths and writes timing.js next to story.js.
// Usage: node scripts/timeline.mjs <story.js> <audioDir>
// Each line starts after the previous one ends, plus its "gap" (default 250 ms). Sound effects are
// anchored to a line ("cue") with an "offset"; a looping bed runs until the start of its "until" line.
import fs from 'node:fs';
import path from 'node:path';
import { readStory, durationMs } from './elevenlabs.mjs';

const [storyFile, audioDir] = process.argv.slice(2);
const story = readStory(storyFile);
const lines = {};
let t = 0;
for (const l of story.lines) {
  const dur = durationMs(path.join(audioDir, `${l.id}.mp3`));
  if (!Number.isFinite(dur)) throw new Error(`missing audio for ${l.id}`);
  t += l.gap ?? 250;
  lines[l.id] = { at: t, dur };
  t += dur;
}
const end = t + (story.tail ?? 2000);
const sfx = Object.fromEntries(story.sfx.map((s) => [s.id, {
  at: Math.max(0, lines[s.cue].at + (s.offset ?? 0)),
  ...(s.until ? { until: lines[s.until].at } : {}),
}]));
const out = path.join(path.dirname(storyFile), 'timing.js');
fs.writeFileSync(out, `// Generated by scripts/timeline.mjs from story.js and the audio lengths. Do not edit.\nwindow.TIMING = ${JSON.stringify({ end, lines, sfx }, null, 1)};\n`);
console.log(`DONE ${out}: ${(end / 1000).toFixed(1)} s`);
